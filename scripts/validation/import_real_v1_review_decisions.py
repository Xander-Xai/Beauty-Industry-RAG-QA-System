#!/usr/bin/env python3
"""Turn signed human review decisions into a formal, schema-valid V1 dataset.

The candidates in ``tests/evaluation/golden_set_v1/candidates_v1.jsonl`` are AI
drafts and stay ``DRAFT_UNVERIFIED`` forever. This script is the missing link
between a *signed* worksheet and a dataset the benchmark will accept. It adds no
review platform: it reads files that already exist and writes files that already
have a home.

Three separation rules shape everything here.

1. **The AI pre-review and the human signature are different files.**
   ``retrieval_review_workpackage.jsonl`` carries ``ai_suggestion`` and
   ``ai_correction`` and is regenerated by its builder. ``review_decisions_v1.jsonl``
   carries only what a person typed, and is never rewritten by any generator. This
   script refuses to read a decision whose row also carries an ``ai_*`` key, so a
   machine suggestion can never be mistaken for a signature.

2. **A decision is bound to the exact candidate bytes it reviewed.**
   Every decision row names ``candidate_sha256`` and ``candidate_dataset_sha256``.
   If the candidate set is regenerated after a review started, the binding breaks
   and the import fails rather than applying a decision to different text.

3. **Nothing is promoted without a name and a date the reviewer chose.**
   There is no ``--reviewer``, no ``--reviewed-at`` and no default reviewer. A row
   whose decision is blank stays ``DRAFT_UNVERIFIED``; a row missing a reviewer, a
   date, or the ``promoted_by`` an ``llm_candidate`` needs is an error, not a silent
   demotion to draft. Dates are read, never generated. **REJECT is held to the same
   identity contract as ACCEPT and MODIFY** -- dropping a sample from the scored
   dataset is a human judgement, not an administrative tidy-up.

4. **The import is all-or-nothing and commits atomically.** One malformed decision
   abandons the entire run: no output is written, any previous formal result is left
   exactly as it was, and the exit code is 2. Outputs are built in full in a scratch
   directory and swapped into place, so a crash cannot leave a directory holding
   half of the new dataset and half of the old.

Usage::

    # emit a blank, hash-bound ledger for a reviewer to sign
    python3 scripts/validation/import_real_v1_review_decisions.py \\
      --emit-template tests/evaluation/golden_set_v1/review_decisions_v1.jsonl

    # report only; writes nothing
    python3 scripts/validation/import_real_v1_review_decisions.py

    # write the outputs once the ledger is signed and entirely valid
    python3 scripts/validation/import_real_v1_review_decisions.py --apply

Exit codes: 0 success (including "signed nothing yet"), 2 refused -- a bad decision,
a broken hash binding, an anonymous verdict, schema drift, or a missing ledger.
"""

from __future__ import annotations

import argparse
import copy
import json
import os
import shutil
import sys
from collections.abc import Mapping, Sequence
from datetime import date
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from benchmarks.annotation import (  # noqa: E402
    ANNOTATION_SOURCE_LLM,
    dataset_sha256,
    load_records,
    promote_to_reviewed,
    record_sha256,
)

DECISION_SCHEMA = "real-corpus-review-decisions/1"
IMPORT_REPORT_SCHEMA = "real-corpus-review-import-report/1"
V1_DATASET_SCHEMA = "real-corpus-golden-set-annotations/1"

DEFAULT_CANDIDATES = "tests/evaluation/golden_set_v1/candidates_v1.jsonl"
DEFAULT_DECISIONS = "tests/evaluation/golden_set_v1/review_decisions_v1.jsonl"
DEFAULT_OUT_DIR = "tests/evaluation/golden_set_v1/reviewed"
V2_SCHEMA_PATH = "tests/evaluation/golden_set_v2/annotations.schema.json"

DECISIONS = ("ACCEPT", "MODIFY", "REJECT")

#: Every key a decision row may carry. The list is closed so an ``ai_*`` field,
#: a stray import flag or a second opinion smuggled in as data is rejected rather
#: than silently ignored.
DECISION_FIELDS = frozenset(
    {
        "decision_schema",
        "sample_id",
        "candidate_sha256",
        "candidate_dataset_sha256",
        "decision",
        "reviewer",
        "reviewed_at",
        "promoted_by",
        "notes",
        "relevance_changes",
        "removed_passages",
        "added_passages",
        "confirmed_difficulty",
        "confirmed_complexity_label",
        "confirmed_business_type",
        "confirmed_question",
    }
)

#: Annotation keys the V2 schema accepts. Everything else (``_locator``,
#: ``_logical_id``, ``contexts``) is review-side provenance and must not reach a
#: formal dataset whose schema sets ``additionalProperties: false``.
ANNOTATION_KEEP = ("doc_id", "chunk_id", "text", "relevance")
RECORD_KEEP = (
    "sample_id",
    "question",
    "business_type",
    "difficulty",
    "visual_required",
    "complexity_label",
    "corpus_version",
    "corpus_sha256",
    "annotations",
    "annotation",
)

DATE_LEN = len("0000-00-00")

V2_SAMPLE_ID_PATTERN = "^[0-9]{4}$"
V2_SAMPLE_ID_DESCRIPTION = (
    "1-based zero-padded line number in the source golden set. Deterministic, so a record always maps back to "
    "its question."
)
V1_SAMPLE_ID_PATTERN = "^REAL-V1-[0-9]{3}$"
V1_SAMPLE_ID_DESCRIPTION = (
    "Stable worksheet identifier shared with candidates_v1.jsonl and "
    "retrieval_review_workpackage.jsonl, so a reviewed record always maps back to the row a human signed."
)


class ImportRefused(Exception):
    """A signed decision could not be applied safely. Nothing is written."""


#: The complete set of schema differences V1 is allowed to have against V2, as
#: ``path: v1_repr != v2_repr``. ``pattern`` is the identifier change that forces a
#: separate V1 schema at all; ``description`` is documentation that cannot weaken a
#: validator. Everything else -- ``required``, ``additionalProperties: false``, the
#: ``REVIEWED`` conditional, every enum -- must be byte-identical, which is what
#: makes this a proof that no V2 gate was relaxed rather than a claim that it was.
ALLOWED_SCHEMA_DIFF = {
    f"properties.sample_id.pattern: {V1_SAMPLE_ID_PATTERN!r} != {V2_SAMPLE_ID_PATTERN!r}",
    f"properties.sample_id.description: {V1_SAMPLE_ID_DESCRIPTION!r} != {V2_SAMPLE_ID_DESCRIPTION!r}",
}


def load_json(path: Path) -> object:
    return json.loads(path.read_text(encoding="utf-8"))


def write_jsonl(path: Path, records: Sequence[Mapping]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")


def is_iso_date(value: object) -> bool:
    if not isinstance(value, str) or len(value) != DATE_LEN:
        return False
    try:
        date.fromisoformat(value)
    except ValueError:
        return False
    return True


def is_sha256(value: object) -> bool:
    return isinstance(value, str) and len(value) == 64 and all(c in "0123456789abcdef" for c in value.lower())


def build_v1_schema() -> dict:
    """Derive the strict V1 schema from the committed V2 schema.

    The V2 schema pins ``sample_id`` to ``^[0-9]{4}$`` because its records are
    numbered lines of one source golden set. The V1 set has its own stable
    ``REAL-V1-001`` identifiers, and rewriting them to four digits would destroy
    the only link back to the worksheet a reviewer actually worked through.

    Rather than copy the schema and hope the two stay aligned, this derives it and
    changes exactly one thing: the ``sample_id`` pattern. Every other constraint --
    ``required``, ``additionalProperties: false``, the ``REVIEWED`` conditional, the
    enums -- is inherited verbatim from V2, so no V2 gate is relaxed. A test pins
    the diff so a later edit to either file cannot silently widen the other.
    """
    v2 = load_json(REPO_ROOT / V2_SCHEMA_PATH)
    v1 = copy.deepcopy(v2)
    v1["$id"] = (
        "https://github.com/Xander-Xai/Beauty-Industry-RAG-QA-System/data/eval/golden_set_v1/annotations.schema.json"
    )
    v1["title"] = "real-corpus-golden-set-annotation/1 record"
    v1["description"] = (
        "One annotation record for the real official corpus V1 golden set. Identical to "
        "golden-set-annotation/v1 (tests/evaluation/golden_set_v2/annotations.schema.json) except that "
        "sample_id is the stable REAL-V1-NNN worksheet identifier instead of a four-digit line number. "
        "Derived by scripts/validation/import_real_v1_review_decisions.py; do not hand-edit."
    )
    v1["properties"]["sample_id"] = {
        "type": "string",
        "pattern": V1_SAMPLE_ID_PATTERN,
        "description": V1_SAMPLE_ID_DESCRIPTION,
    }
    return v1


def schema_diff(v1: Mapping, v2: Mapping) -> list[str]:
    """Return every path where the two schemas differ, ignoring ``$id``/titles.

    ``$id``, ``title`` and ``description`` at the document root are metadata that
    cannot weaken validation, so they are not differences for this purpose.
    """
    pinned = {"$id", "title", "description"}
    differences: list[str] = []

    def walk(left: object, right: object, path: str) -> None:
        if isinstance(left, Mapping) and isinstance(right, Mapping):
            for key in sorted(set(left) | set(right)):
                if path == "" and key in pinned:
                    continue
                walk(left.get(key), right.get(key), f"{path}.{key}" if path else key)
            return
        if isinstance(left, list) and isinstance(right, list):
            if len(left) != len(right):
                differences.append(f"{path}: length {len(left)} != {len(right)}")
                return
            for index, (a, b) in enumerate(zip(left, right, strict=True)):
                walk(a, b, f"{path}[{index}]")
            return
        if left != right:
            differences.append(f"{path}: {left!r} != {right!r}")

    walk(v1, v2, "")
    return differences


def assert_schema_not_relaxed(v1: Mapping, v2: Mapping) -> list[str]:
    """Fail unless the V1 schema differs from V2 in exactly the allowed way."""
    differences = schema_diff(v1, v2)
    unexpected = sorted(set(differences) - ALLOWED_SCHEMA_DIFF)
    missing = sorted(ALLOWED_SCHEMA_DIFF - set(differences))
    if unexpected:
        raise ImportRefused(
            "the V1 schema diverges from V2 outside the sample_id identifier, which would mean a V2 gate was "
            f"relaxed: {'; '.join(unexpected)}"
        )
    if missing:
        raise ImportRefused(
            "the V1 schema is identical to V2, so its sample_id pattern was not derived as intended: "
            f"{'; '.join(missing)}"
        )
    return differences


def v2_compatible_id(sample_id: str) -> str:
    """Map ``REAL-V1-007`` to the four-digit V2 form ``0007``.

    ``^REAL-V1-[0-9]{3}$`` bounds the numeric part to 000-999, so zero-padding to
    four digits is injective over the V1 set and no two V1 ids collide. The map
    is kept so a reviewed record can be re-checked against the untouched V2 schema
    without weakening it; it is *not* used for scoring, and the emitted dataset
    keeps ``REAL-V1-NNN``.
    """
    suffix = sample_id.rsplit("-", 1)[-1]
    if not (suffix.isdigit() and len(suffix) == 3):
        raise ImportRefused(f"sample_id {sample_id!r} does not match the V1 pattern; cannot map it to the V2 form")
    return suffix.zfill(4)


def validate_decision_shape(decision: Mapping, sample_id: str) -> None:
    unknown = sorted(set(decision) - DECISION_FIELDS)
    if unknown:
        raise ImportRefused(
            f"{sample_id}: decision carries fields outside the human-decision schema: {', '.join(unknown)}. "
            "AI pre-review belongs in the workpackage, never in the signed ledger."
        )


def apply_decision(candidate: Mapping, decision: Mapping) -> dict:
    """Return the candidate with the reviewer's edits applied, still unpromoted."""
    updated = copy.deepcopy(dict(candidate))
    annotations = [dict(a) for a in updated.get("annotations", [])]
    by_chunk = {str(a.get("chunk_id")): a for a in annotations}

    for change in decision.get("relevance_changes") or []:
        chunk_id = str(change.get("chunk_id") or "")
        if chunk_id not in by_chunk:
            raise ImportRefused(f"{decision['sample_id']}: relevance_change names unknown chunk_id {chunk_id!r}")
        target = change.get("to")
        if target not in (0, 1, 2):
            raise ImportRefused(f"{decision['sample_id']}: relevance_change.to must be 0, 1 or 2, got {target!r}")
        by_chunk[chunk_id]["relevance"] = int(target)

    for removal in decision.get("removed_passages") or []:
        chunk_id = str(removal.get("chunk_id") or "")
        if chunk_id not in by_chunk:
            raise ImportRefused(f"{decision['sample_id']}: removed_passages names unknown chunk_id {chunk_id!r}")
        if by_chunk[chunk_id].get("relevance") == 0:
            continue
        # relevance 0 is the documented way to record "considered and excluded";
        # it stays in the row so the exclusion is auditable, and it does not enter
        # the binary relevant set (GRADE_THRESHOLD_RELEVANT = 1).
        by_chunk[chunk_id]["relevance"] = 0

    for addition in decision.get("added_passages") or []:
        for field in ("doc_id", "chunk_id", "text"):
            if not str(addition.get(field) or ""):
                raise ImportRefused(f"{decision['sample_id']}: added_passage is missing {field}")
        if str(addition["chunk_id"]) in by_chunk:
            raise ImportRefused(
                f"{decision['sample_id']}: added_passage duplicates existing chunk {addition['chunk_id']}"
            )
        relevance = addition.get("relevance", 2)
        if relevance not in (0, 1, 2):
            raise ImportRefused(f"{decision['sample_id']}: added_passage.relevance must be 0, 1 or 2")
        by_chunk[str(addition["chunk_id"])] = {
            "doc_id": str(addition["doc_id"]),
            "chunk_id": str(addition["chunk_id"]),
            "text": str(addition["text"]),
            "relevance": int(relevance),
        }

    updated["annotations"] = list(by_chunk.values())

    for field in ("difficulty", "complexity_label", "business_type", "question"):
        confirmed = decision.get(f"confirmed_{field}")
        if confirmed:
            updated[field] = confirmed

    note = decision.get("notes")
    if note:
        provenance = dict(updated["annotation"])
        provenance["notes"] = f"{provenance.get('notes', '')} | human_review: {note}".strip(" |")
        updated["annotation"] = provenance

    return updated


def require_human_decision(candidate: Mapping, decision: Mapping) -> None:
    """Enforce the real-human contract that every non-empty decision must meet.

    This runs for ACCEPT, MODIFY **and** REJECT. Excluding a candidate is a
    human judgement about a real candidate: an anonymous rejection is
    indistinguishable from a row somebody deleted because it was inconvenient, and
    it permanently removes a sample from the scored dataset with no attributable
    record of who decided that. A rejection is not a lighter decision than an
    acceptance, so it carries the same identity requirement.

    ``promoted_by`` is deliberately *not* required here. It records who promoted an
    ``llm_candidate`` to ``REVIEWED``; a REJECT performs no promotion, so demanding
    it would ask for a field that has no honest value.
    """
    sample_id = str(candidate["sample_id"])
    reviewer = decision.get("reviewer")
    reviewed_at = decision.get("reviewed_at")

    if not str(reviewer or "").strip():
        raise ImportRefused(
            f"{sample_id}: every non-empty decision needs a named reviewer; none was recorded. "
            "An unsigned or anonymous verdict is refused for ACCEPT, MODIFY and REJECT alike."
        )
    if not is_iso_date(reviewed_at):
        raise ImportRefused(
            f"{sample_id}: reviewed_at must be the ISO date the reviewer actually decided on, got {reviewed_at!r}. "
            "This script never supplies a date."
        )
    annotator = str((candidate.get("annotation") or {}).get("annotator") or "")
    if reviewer == annotator:
        raise ImportRefused(
            f"{sample_id}: reviewer {reviewer!r} is the original annotator; self-review defeats the second pair of eyes"
        )


def require_promotion_attribution(candidate: Mapping, decision: Mapping) -> None:
    """An ``llm_candidate`` may only reach REVIEWED through a named promoter."""
    if (candidate.get("annotation") or {}).get("source") == ANNOTATION_SOURCE_LLM and not str(
        decision.get("promoted_by") or ""
    ).strip():
        raise ImportRefused(
            f"{candidate['sample_id']}: an llm_candidate can only be promoted with a real promoted_by, "
            "so the promotion itself is auditable"
        )


def promote(candidate: Mapping, decision: Mapping) -> dict:
    """Apply the decision and promote it, refusing every unsafe combination."""
    require_human_decision(candidate, decision)
    require_promotion_attribution(candidate, decision)
    promoted_by = str(decision.get("promoted_by") or "").strip()
    updated = apply_decision(candidate, decision)
    return promote_to_reviewed(
        updated,
        reviewer=str(decision["reviewer"]),
        reviewed_at=str(decision["reviewed_at"]),
        promoted_by=promoted_by or None,
    )


def project_to_schema(record: Mapping) -> dict:
    """Strip review-side fields so the record satisfies the formal schema."""
    projected = {field: record[field] for field in RECORD_KEEP}
    projected["annotations"] = [
        {field: a[field] for field in ANNOTATION_KEEP if field in a} for a in record["annotations"]
    ]
    projected["annotation"] = {key: value for key, value in record["annotation"].items()}
    return projected


def emit_template(candidates: Sequence[Mapping], path: Path, candidate_set_sha: str) -> int:
    """Write a blank, hash-bound decision ledger for a reviewer to sign.

    The template pre-fills only what a machine can know truthfully: the sample id
    and the two hashes that bind the decision to the exact candidate bytes. Every
    human field is emitted blank -- ``decision``, ``reviewer``, ``reviewed_at``,
    ``promoted_by``, ``notes`` -- because this script has no authority to fill
    them and must never appear to have done so.

    It refuses to overwrite an existing ledger. Once a reviewer has signed, that
    file is the only record that a human decision was ever made for these samples,
    and a rebuilt template must not be able to erase it.
    """
    if path.exists():
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            row = json.loads(line)
            if any(str(row.get(field) or "").strip() for field in ("decision", "reviewer", "reviewed_at")):
                print(f"REFUSED: {path} already carries signed decisions; move it aside before emitting a new template")
                return 2
    template = [
        {
            "decision_schema": DECISION_SCHEMA,
            "sample_id": record["sample_id"],
            "candidate_sha256": record_sha256(record),
            "candidate_dataset_sha256": candidate_set_sha,
            "decision": "",
            "reviewer": "",
            "reviewed_at": "",
            "promoted_by": "",
            "notes": "",
            "relevance_changes": [],
            "removed_passages": [],
            "added_passages": [],
            "confirmed_difficulty": "",
            "confirmed_complexity_label": "",
            "confirmed_business_type": "",
            "confirmed_question": "",
        }
        for record in candidates
    ]
    write_jsonl(path, template)
    print(f"blank decision ledger for {len(template)} samples: {path}")
    print(f"bound to candidate_dataset_sha256 {candidate_set_sha}")
    print("fill decision / reviewer / reviewed_at (and promoted_by for llm_candidate rows), then re-run the importer")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--candidates", default=DEFAULT_CANDIDATES)
    parser.add_argument("--decisions", default=DEFAULT_DECISIONS)
    parser.add_argument("--out-dir", default=DEFAULT_OUT_DIR)
    parser.add_argument(
        "--apply",
        action="store_true",
        help="write the outputs; without it this is a dry run and nothing is created",
    )
    parser.add_argument(
        "--emit-template",
        metavar="PATH",
        help="write a blank, hash-bound decision ledger for a reviewer to sign, then exit",
    )
    args = parser.parse_args(argv)

    candidates_path = Path(args.candidates)
    decisions_path = Path(args.decisions)
    out_dir = Path(args.out_dir)

    candidates = load_records(candidates_path)
    by_id = {str(record["sample_id"]): record for record in candidates}
    if len(by_id) != len(candidates):
        raise SystemExit("candidate set contains duplicate sample_id values")

    if args.emit_template:
        return emit_template(candidates, Path(args.emit_template), dataset_sha256(candidates_path))

    decisions: dict[str, dict] = {}
    refusals: list[str] = []
    if decisions_path.exists():
        for row in load_records(decisions_path):
            sample_id = str(row.get("sample_id") or "")
            if sample_id in decisions:
                refusals.append(f"{sample_id}: more than one decision row")
            decisions[sample_id] = dict(row)
    else:
        refusals.append(
            f"no decision ledger at {decisions_path}; create it from the worksheet and sign it before importing"
        )

    candidate_set_sha = dataset_sha256(candidates_path)

    reviewed: list[dict] = []
    drafts: list[dict] = []
    rejected: list[dict] = []
    ledger: list[dict] = []
    counts = {"ACCEPT": 0, "MODIFY": 0, "REJECT": 0, "UNSIGNED": 0}

    for sample_id in sorted(by_id):
        candidate = by_id[sample_id]
        decision = decisions.get(sample_id)
        if decision is None:
            counts["UNSIGNED"] += 1
            drafts.append(project_to_schema(candidate))
            continue

        try:
            validate_decision_shape(decision, sample_id)
            if str(decision.get("decision_schema") or DECISION_SCHEMA) != DECISION_SCHEMA:
                raise ImportRefused(
                    f"{sample_id}: decision_schema {decision.get('decision_schema')!r} is not {DECISION_SCHEMA!r}"
                )
            if not is_sha256(decision.get("candidate_sha256")):
                raise ImportRefused(f"{sample_id}: decision does not bind candidate_sha256")
            if decision["candidate_sha256"] != record_sha256(candidate):
                raise ImportRefused(
                    f"{sample_id}: decision binds candidate_sha256 {decision['candidate_sha256'][:12]}…, but the "
                    f"candidate now hashes to {record_sha256(candidate)[:12]}…; the candidate set was regenerated after "
                    "this review started, so the decision no longer applies to these bytes"
                )
            bound_set = decision.get("candidate_dataset_sha256")
            if bound_set and str(bound_set) != candidate_set_sha:
                raise ImportRefused(
                    f"{sample_id}: decision binds candidate_dataset_sha256 {str(bound_set)[:12]}…, but the candidate "
                    f"file hashes to {candidate_set_sha[:12]}…"
                )

            verdict = str(decision.get("decision") or "")
            if not verdict.strip():
                # A row the reviewer has not reached yet is not a malformed
                # decision, it is an unsigned one. It stays DRAFT_UNVERIFIED and
                # counts as such, so the report shows how far the review got.
                counts["UNSIGNED"] += 1
                drafts.append(project_to_schema(candidate))
                continue
            if verdict not in DECISIONS:
                raise ImportRefused(f"{sample_id}: decision must be one of {DECISIONS}, got {verdict!r}")

            ledger.append({"sample_id": sample_id, "decision": verdict})

            if verdict == "REJECT":
                # A rejected candidate never enters the scored dataset. It is
                # recorded so the exclusion is auditable rather than a silent drop.
                # Rejecting is a human decision like any other, so it carries the
                # same identity contract: no anonymous removals.
                require_human_decision(candidate, decision)
                rejected.append(project_to_schema(apply_decision(candidate, decision)))
                counts["REJECT"] += 1
                continue

            record = promote(candidate, decision)
            reviewed.append(project_to_schema(record))
            counts[verdict] += 1
        except ImportRefused as exc:
            refusals.append(str(exc))
            # A refused decision must not silently become a draft: an unsigned or
            # broken row stays out of the scored dataset either way.
            drafts.append(project_to_schema(candidate))

    v1_schema = build_v1_schema()
    v2_schema = load_json(REPO_ROOT / V2_SCHEMA_PATH)
    try:
        differences = assert_schema_not_relaxed(v1_schema, v2_schema)
        # Built before anything is written so a malformed id fails the run rather
        # than half of it. Injective over the V1 pattern, which the test pins.
        id_map = {record["sample_id"]: v2_compatible_id(str(record["sample_id"])) for record in reviewed + rejected}
        if len(set(id_map.values())) != len(id_map):
            raise ImportRefused("the REAL-V1-NNN to V2 identifier mapping is not injective; it would not be lossless")
    except ImportRefused as exc:
        refusals.append(str(exc))
        differences = schema_diff(v1_schema, v2_schema)
        id_map = {}

    report = {
        "schema": IMPORT_REPORT_SCHEMA,
        "candidate_dataset": str(candidates_path),
        "candidate_dataset_sha256": candidate_set_sha,
        "candidate_count": len(candidates),
        "decision_ledger": str(decisions_path),
        "decision_ledger_sha256": dataset_sha256(decisions_path) if decisions_path.exists() else "",
        "counts": counts,
        "reviewed_rows": len(reviewed),
        "draft_rows": len(drafts),
        "rejected_rows": len(rejected),
        "scorable_rows": len(reviewed),
        "v1_schema_diff_vs_v2": differences,
        "v1_dataset_schema": V1_DATASET_SCHEMA,
        "refusals": refusals,
        "applied": bool(args.apply),
        "note": (
            "An empty review ledger is not an error: the candidates are drafts and stay "
            "DRAFT_UNVERIFIED until a named reviewer signs them."
        ),
    }

    if refusals:
        # All-or-nothing. A ledger where one row is malformed is a ledger whose
        # remaining rows cannot be trusted as a set: the reviewer may have signed
        # it against a candidate set that has since moved, and a partial import
        # would publish a formal dataset that silently mixes old and new bytes.
        # Nothing is written and any previous formal result is left untouched.
        print(f"REFUSED: {len(refusals)} problem(s); the whole import was abandoned and nothing was written")
        for refusal in refusals:
            print(f"  - {refusal}")
        return 2

    print(f"candidates: {len(candidates)}")
    print(f"decisions: {counts}")
    print(f"reviewed (scorable): {len(reviewed)}")
    print(f"still draft: {len(drafts)}")
    print(f"rejected: {len(rejected)}")
    print(f"v1 schema diff vs v2 (must be sample_id only): {differences}")

    if not args.apply:
        print("dry run; nothing written (pass --apply to write)")
        return 0

    # Every output is built in full, in a scratch directory, before anything the
    # previous run produced is touched. A crash between two file writes can then
    # never leave a directory holding half of the new dataset and half of the old.
    staging = out_dir.parent / f".{out_dir.name}.staging-{os.getpid()}"
    backup = out_dir.parent / f".{out_dir.name}.previous-{os.getpid()}"
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir(parents=True)
    try:
        write_jsonl(staging / "review_decisions_applied.jsonl", ledger)
        write_jsonl(staging / "annotations_v1_reviewed.jsonl", reviewed)
        write_jsonl(staging / "annotations_v1_drafts.jsonl", drafts)
        write_jsonl(staging / "annotations_v1_rejected.jsonl", rejected)
        write_jsonl(
            staging / "sample_id_map_v2.jsonl",
            [
                {
                    "v1_sample_id": sample_id,
                    "v2_sample_id": v2_id,
                    "mapping": (
                        "suffix zero-padded to four digits; V1 identifiers are what the worksheet and candidates use"
                    ),
                }
                for sample_id, v2_id in sorted(id_map.items())
            ],
        )
        (staging / "annotations_v1.schema.json").write_text(
            json.dumps(v1_schema, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )
        (staging / "import_report.json").write_text(
            json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
        if out_dir.exists():
            os.replace(out_dir, backup)
        try:
            os.replace(staging, out_dir)
        except OSError:
            if backup.exists():
                os.replace(backup, out_dir)
            raise
    finally:
        if staging.exists():
            shutil.rmtree(staging, ignore_errors=True)
        if backup.exists():
            shutil.rmtree(backup, ignore_errors=True)

    for name in (
        "review_decisions_applied.jsonl",
        "annotations_v1_reviewed.jsonl",
        "annotations_v1_drafts.jsonl",
        "annotations_v1_rejected.jsonl",
        "sample_id_map_v2.jsonl",
        "annotations_v1.schema.json",
        "import_report.json",
    ):
        print(f"wrote: {out_dir / name}")
    return 0


