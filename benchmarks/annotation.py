"""Human annotation record schema, review lifecycle and audit.

The problem this solves
-----------------------
``golden-set-contract/v2`` requires provenance (``annotator`` / ``method`` /
``annotated_at`` / ``reviewed_by``) but has no notion of *review state*. A record
generated by an LLM and a record a person reviewed are therefore shaped
identically, so an unverified machine proposal can be dropped into a dataset and
score like ground truth.

This module makes review state explicit and fail-closed:

* ``review_status`` is **required** and has no default. Its absence is an error,
  not an implicit ``REVIEWED``. A record that forgets to say whether a human
  looked at it cannot enter a scored run.
* :data:`REVIEW_STATUS_DRAFT` marks an unreviewed candidate. Such a record is
  **never** eligible for official scoring, whatever else it carries.
* A record whose :data:`ANNOTATION_SOURCE_LLM` was generated by a model can only
  become :data:`REVIEW_STATUS_REVIEWED` through an explicit promotion that names
  the human reviewer and records when. Promotion is auditable, never implicit.
* Every record is bound to a ``corpus_version`` **and** the SHA-256 of the
  corpus it was mapped against, so a mapping cannot silently outlive the index
  it was built for.

Nothing here fabricates a review. :func:`promote_to_reviewed` refuses to invent a
reviewer; there is no default annotator, no inferred ``reviewed_by`` and no
"assume approved" path. Promoting is an explicit act by a named person.

This module only *describes and checks* records. It does not produce labels; the
labeling work itself is a human task and is enumerated in
``tests/evaluation/golden_set_v2/HUMAN_ANNOTATION_BACKLOG.md``.
"""

from __future__ import annotations

import hashlib
import json
import re
from collections.abc import Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from benchmarks.models import RELEVANCE_GRADE_NAMES, RELEVANCE_GRADES

ANNOTATION_SCHEMA_VERSION = "golden-set-annotation/v1"

#: The candidate was produced (possibly by an LLM) and nobody has reviewed it.
REVIEW_STATUS_DRAFT = "DRAFT_UNVERIFIED"
#: A named human has reviewed and accepted the record.
REVIEW_STATUS_REVIEWED = "REVIEWED"

REVIEW_STATUSES = (REVIEW_STATUS_DRAFT, REVIEW_STATUS_REVIEWED)

#: A person mapped the passage.
ANNOTATION_SOURCE_HUMAN = "human"
#: A model proposed the mapping; it is a candidate until a human accepts it.
ANNOTATION_SOURCE_LLM = "llm_candidate"

ANNOTATION_SOURCES = (ANNOTATION_SOURCE_HUMAN, ANNOTATION_SOURCE_LLM)

#: Only a reviewed record may contribute ground truth to a scored run.
SCORABLE_REVIEW_STATUS = REVIEW_STATUS_REVIEWED

_CORPUS_VERSION_RE = re.compile(r"^[A-Za-z0-9_.\-]{2,64}$")
_SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
_DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")

REQUIRED_PROVENANCE_FIELDS = ("annotator", "method", "annotated_at", "review_status", "source")


class AnnotationError(ValueError):
    """Raised when an annotation record violates the schema."""


@dataclass(frozen=True)
class AnnotationVerdict:
    """Per-record audit result with machine-readable reasons."""

    sample_id: str
    valid: bool
    scorable: bool
    reasons: tuple[str, ...] = ()

    def as_dict(self) -> dict[str, Any]:
        return {
            "sample_id": self.sample_id,
            "valid": self.valid,
            "scorable": self.scorable,
            "reasons": list(self.reasons),
        }


@dataclass(frozen=True)
class AnnotationReport:
    """Dataset-level audit result."""

    schema_version: str
    total: int
    valid_count: int
    scorable_count: int
    draft_count: int
    verdicts: tuple[AnnotationVerdict, ...] = field(default=())
    corpus_versions: tuple[str, ...] = field(default=())
    corpus_sha256: str | None = None

    def as_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "total": self.total,
            "valid_count": self.valid_count,
            "scorable_count": self.scorable_count,
            "draft_count": self.draft_count,
            "corpus_versions": list(self.corpus_versions),
            "corpus_sha256": self.corpus_sha256,
            "verdicts": [verdict.as_dict() for verdict in self.verdicts],
        }

    def invalid_reasons(self) -> dict[str, int]:
        counts: dict[str, int] = {}
        for verdict in self.verdicts:
            for reason in verdict.reasons:
                counts[reason] = counts.get(reason, 0) + 1
        return counts


def _is_nonempty_str(value: Any) -> bool:
    return isinstance(value, str) and bool(value.strip())


def validate_annotation(record: Mapping[str, Any], index: int = 0) -> AnnotationVerdict:
    """Validate one annotation record. Never infers a missing review decision.

    Returns a verdict rather than raising so a dataset audit can report every
    broken record at once instead of stopping at the first.
    """
    sample_id = str(record.get("sample_id") or f"<row {index}>")
    reasons: list[str] = []

    if not _is_nonempty_str(record.get("sample_id")):
        reasons.append("missing_sample_id")
    if not _is_nonempty_str(record.get("question")):
        reasons.append("missing_question")

    corpus_version = record.get("corpus_version")
    if not _is_nonempty_str(corpus_version) or not _CORPUS_VERSION_RE.match(str(corpus_version)):
        reasons.append("missing_or_invalid_corpus_version")

    corpus_sha = record.get("corpus_sha256")
    if not _is_nonempty_str(corpus_sha) or not _SHA256_RE.match(str(corpus_sha).lower()):
        # The mapping is only meaningful against a known corpus state. Without a
        # hash, a chunk id could silently refer to a different index revision.
        reasons.append("missing_or_invalid_corpus_sha256")

    for flag in ("visual_required",):
        if not isinstance(record.get(flag), bool):
            reasons.append(f"missing_{flag}")

    annotations = record.get("annotations")
    if not isinstance(annotations, list) or not annotations:
        reasons.append("missing_annotations")
    else:
        seen_keys: set[tuple[str, str]] = set()
        for position, annotation in enumerate(annotations):
            if not isinstance(annotation, Mapping):
                reasons.append(f"annotation_{position}_not_an_object")
                continue
            for required in ("doc_id", "chunk_id", "text"):
                if not _is_nonempty_str(annotation.get(required)):
                    reasons.append(f"annotation_{position}_missing_{required}")
            grade = annotation.get("relevance", RELEVANCE_GRADES[-1])
            if isinstance(grade, bool) or not isinstance(grade, int) or grade not in RELEVANCE_GRADES:
                reasons.append(f"annotation_{position}_invalid_relevance_grade")
            # A duplicate (doc_id, chunk_id) means the same passage was recorded
            # twice, which would double-count it in Recall's denominator.
            key = (str(annotation.get("doc_id")), str(annotation.get("chunk_id")))
            if key in seen_keys:
                reasons.append(f"annotation_{position}_duplicate_chunk")
            seen_keys.add(key)

    provenance = record.get("annotation")
    if not isinstance(provenance, Mapping):
        reasons.append("missing_annotation_provenance")
        source = None
        review_status = None
    else:
        for required in REQUIRED_PROVENANCE_FIELDS:
            if not _is_nonempty_str(provenance.get(required)):
                reasons.append(f"missing_annotation_{required}")
        annotated_at = provenance.get("annotated_at")
        if _is_nonempty_str(annotated_at) and not _DATE_RE.match(str(annotated_at)):
            reasons.append("annotation_annotated_at_not_iso_date")
        source = provenance.get("source")
        review_status = provenance.get("review_status")

    if _is_nonempty_str(source) and source not in ANNOTATION_SOURCES:
        reasons.append("annotation_invalid_source")

    valid_review_status = _is_nonempty_str(review_status) and review_status in REVIEW_STATUSES
    if _is_nonempty_str(review_status) and not valid_review_status:
        reasons.append("annotation_invalid_review_status")

    # A reviewed record must say who reviewed it and when. This is the clause
    # that stops an LLM candidate from being relabelled as approved.
    if valid_review_status and review_status == REVIEW_STATUS_REVIEWED:
        if not isinstance(provenance, Mapping) or not _is_nonempty_str(provenance.get("reviewed_by")):
            reasons.append("missing_annotation_reviewed_by")
        reviewed_at = (provenance or {}).get("reviewed_at")
        if not _is_nonempty_str(reviewed_at) or not _DATE_RE.match(str(reviewed_at)):
            reasons.append("missing_or_invalid_annotation_reviewed_at")
        # Self-review defeats the point of a second pair of eyes.
        if _is_nonempty_str((provenance or {}).get("reviewed_by")) and (
            (provenance or {}).get("reviewed_by") == (provenance or {}).get("annotator")
        ):
            reasons.append("annotation_self_reviewed")

    if _is_nonempty_str(source) and source == ANNOTATION_SOURCE_LLM and review_status == REVIEW_STATUS_REVIEWED:
        # Promotion from a model proposal is allowed, but only through the
        # reviewed_by clause above — never by relabelling the record.
        if not _is_nonempty_str((provenance or {}).get("promoted_by")):
            reasons.append("annotation_llm_promotion_requires_promoted_by")

    if _is_nonempty_str(source) and source == ANNOTATION_SOURCE_HUMAN and valid_review_status:
        if review_status == REVIEW_STATUS_DRAFT and _is_nonempty_str(provenance.get("reviewed_by")):
            # A draft must not simultaneously claim to be reviewed.
            reasons.append("annotation_draft_claims_reviewed_by")

    valid = not reasons
    scorable = valid and review_status == SCORABLE_REVIEW_STATUS
    return AnnotationVerdict(sample_id=sample_id, valid=valid, scorable=scorable, reasons=tuple(reasons))


def audit_dataset(records: Sequence[Mapping[str, Any]]) -> AnnotationReport:
    """Audit every record and summarize the review state of the dataset."""
    verdicts = [
        validate_annotation(record, index)
        for index, record in enumerate(records)
    ]
    corpus_versions = sorted(
        {str(record.get("corpus_version")) for record in records if _is_nonempty_str(record.get("corpus_version"))}
    )
    corpus_hashes = {
        str(record.get("corpus_sha256")).lower()
        for record in records
        if _is_nonempty_str(record.get("corpus_sha256"))
    }

    # A dataset mapped against two different corpus states cannot be scored as
    # one dataset; the ids refer to different things. Every record is marked so
    # the failure is visible on each row, not only in a summary line.
    mixed_corpus = len(corpus_hashes) > 1
    if mixed_corpus:
        verdicts = [
            AnnotationVerdict(
                sample_id=verdict.sample_id,
                valid=False,
                scorable=False,
                reasons=(*verdict.reasons, "mixed_corpus_sha256_in_dataset"),
            )
            for verdict in verdicts
        ]

    statuses = [_review_status_of(record) for record in records]
    draft_count = sum(1 for status in statuses if status == REVIEW_STATUS_DRAFT)

    return AnnotationReport(
        schema_version=ANNOTATION_SCHEMA_VERSION,
        total=len(records),
        valid_count=sum(1 for verdict in verdicts if verdict.valid),
        scorable_count=sum(1 for verdict in verdicts if verdict.scorable),
        draft_count=draft_count,
        verdicts=tuple(verdicts),
        corpus_versions=tuple(corpus_versions),
        corpus_sha256=next(iter(corpus_hashes)) if len(corpus_hashes) == 1 else None,
    )


def _review_status_of(record: Mapping[str, Any]) -> str | None:
    provenance = record.get("annotation")
    if not isinstance(provenance, Mapping):
        return None
    status = provenance.get("review_status")
    return str(status) if _is_nonempty_str(status) else None


def load_records(path: str | Path) -> list[dict[str, Any]]:
    """Load a JSONL annotation dataset.

    An **empty** file is a valid input and returns ``[]``: the committed
    annotation datasets ship empty on purpose, because the labeling is a human
    task that has not been performed. A missing file, a malformed line or a
    non-object line is an error — those mean the dataset is corrupt, not blank.
    """
    path = Path(path)
    if not path.exists():
        raise AnnotationError(f"{path}: annotation dataset does not exist")
    records: list[dict[str, Any]] = []
    with open(path, encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                decoded = json.loads(line)
            except json.JSONDecodeError as exc:
                raise AnnotationError(f"{path}:{line_number}: invalid JSON ({exc})") from exc
            if not isinstance(decoded, Mapping):
                raise AnnotationError(f"{path}:{line_number}: each line must be a JSON object")
            records.append(dict(decoded))
    return records


def promote_to_reviewed(
    record: Mapping[str, Any],
    reviewer: str,
    reviewed_at: str,
    *,
    promoted_by: str | None = None,
) -> dict[str, Any]:
    """Return a copy of ``record`` promoted to :data:`REVIEW_STATUS_REVIEWED`.

    This is the *only* path by which a draft becomes scorable, and it requires a
    named reviewer and a date. It deliberately refuses to fill in a missing
    ``annotator`` or invent provenance: a draft that does not record who made it
    cannot be audited later, so promoting it would launder an unknown origin
    under a real reviewer's name.
    """
    if not _is_nonempty_str(reviewer):
        raise AnnotationError("a promotion requires a named reviewer")
    if not _DATE_RE.match(str(reviewed_at or "")):
        raise AnnotationError("a promotion requires an ISO reviewed_at date")
    provenance = record.get("annotation")
    if not isinstance(provenance, Mapping):
        raise AnnotationError("record has no annotation provenance to promote")
    if not _is_nonempty_str(provenance.get("annotator")):
        raise AnnotationError(
            "record has no named annotator; promotion would attribute it to an unknown origin"
        )
    if provenance.get("reviewed_by") not in (None, "") and str(provenance.get("reviewed_by")) == reviewer:
        raise AnnotationError(f"{reviewer} already recorded as the reviewer of this record")

    promoted = dict(record)
    new_provenance = dict(provenance)
    new_provenance["review_status"] = REVIEW_STATUS_REVIEWED
    new_provenance["reviewed_by"] = reviewer
    new_provenance["reviewed_at"] = reviewed_at
    if promoted_by is not None:
        new_provenance["promoted_by"] = promoted_by
    promoted["annotation"] = new_provenance
    return promoted


def grade_name(grade: int) -> str:
    return RELEVANCE_GRADE_NAMES.get(grade, f"unknown({grade})")


def record_sha256(record: Mapping[str, Any]) -> str:
    """Stable digest of one record, for pinning what was audited."""
    payload = json.dumps(record, ensure_ascii=False, sort_keys=True)
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def dataset_sha256(path: str | Path) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(65536), b""):
            digest.update(block)
    return digest.hexdigest()
